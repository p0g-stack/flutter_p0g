#!/usr/bin/env sh
# Resolves flutter_p0g_tool on its own, for development and CI.
#
# Stock Flutter's pub cannot resolve flutter_tools as `sdk: flutter`, so it
# needs a path override. This writes that override into
# pubspec_overrides.yaml (gitignored) for the SDK at $FLUTTER_ROOT, or the
# `flutter` on PATH, then runs `flutter pub get`.
# Extra arguments go to `pub get` (for example --offline).
#
# A pubspec_overrides.yaml this script did not write is left alone.
set -eu

marker='# Generated by tool/resolve.sh; delete to customize.'
package=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
overrides="$package/pubspec_overrides.yaml"

if [ -z "${FLUTTER_ROOT:-}" ]; then
  flutter=$(command -v flutter) || {
    echo 'resolve.sh: set FLUTTER_ROOT or put flutter on PATH.' >&2
    exit 1
  }
  FLUTTER_ROOT=$(dirname -- "$(dirname -- "$(readlink -f -- "$flutter")")")
fi
FLUTTER_ROOT=$(CDPATH='' cd -- "$FLUTTER_ROOT" && pwd)
export FLUTTER_ROOT

tools="$FLUTTER_ROOT/packages/flutter_tools"
if [ ! -f "$tools/pubspec.yaml" ]; then
  echo "resolve.sh: $tools/pubspec.yaml not found; is FLUTTER_ROOT a Flutter SDK?" >&2
  exit 1
fi

if [ -f "$overrides" ] && [ "$(head -n 1 -- "$overrides")" != "$marker" ]; then
  if ! grep -q '^[[:space:]]*flutter_tools:' "$overrides"; then
    echo "resolve.sh: $overrides is yours and does not override flutter_tools." >&2
    echo "Add under dependency_overrides:" >&2
    echo "  flutter_tools:" >&2
    echo "    path: $tools" >&2
    exit 1
  fi
  echo "resolve.sh: keeping your $overrides." >&2
else
  # YAML single quotes: a literal ' is written ''.
  quoted=$(printf '%s' "$tools" | sed "s/'/''/g")
  tmp="$overrides.tmp.$$"
  printf '%s\ndependency_overrides:\n  flutter_tools:\n    path: '\''%s'\''\n' \
    "$marker" "$quoted" >"$tmp"
  mv -f -- "$tmp" "$overrides"
fi

cd -- "$package"
exec "$FLUTTER_ROOT/bin/flutter" pub get "$@"
